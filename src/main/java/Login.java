    private void logInjButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_logInjButtonActionPerformed
        // TODO add your handling code here:
        String userName = userNamejTextField.getText().trim();
        String password = new String(jPasswordField.getPassword()).trim();

        if (userName.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter your name and password!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (users.containsKey(userName) && users.get(userName).equals(password)) {
            if (userName.equals("admin")) {
                new ServerChat().setVisible(true);
            } else {
                new ClientChat(userName).setVisible(true);
            }
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Wrong username or password!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            jPasswordField.setText("");
            jPasswordField.requestFocus();
        }
    }//GEN-LAST:event_logInjButtonActionPerformed

