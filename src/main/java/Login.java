    private final java.util.Map<String, String> users = new java.util.HashMap<>();

    private void loadUsers() {
        try {
            java.io.File file = new java.io.File("resources/users.txt");

            if (!file.exists()) {
                javax.swing.JOptionPane.showMessageDialog(this, "users.txt not found at: " + file.getAbsolutePath(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            java.util.Scanner fileScanner = new java.util.Scanner(file);
            while (fileScanner.hasNextLine()) {
                String line = fileScanner.nextLine().trim();
                if (!line.isEmpty()) {
                    String[] parts = line.split(":");
                    users.put(parts[0], parts[1]);
                }
            }

        } catch (HeadlessException | FileNotFoundException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
