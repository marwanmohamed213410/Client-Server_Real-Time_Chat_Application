    private void signUpjButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_signUpjButtonActionPerformed
        // TODO add your handling code here:
        String userName = userNamejTextField.getText().trim();
        String password = new String(jPasswordField.getPassword()).trim();
        String confirm = new String(jPasswordConfirmField.getPassword()).trim();

        if (userName.isEmpty() || password.isEmpty() || confirm.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill all fields!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (!password.equals(confirm)) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Passwords do not match!", "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            jPasswordConfirmField.setText("");
            return;
        }

        if (isUserExists(userName)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Username already exists!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        saveUser(userName, password);

        javax.swing.JOptionPane.showMessageDialog(this, "Account created! You can now login.", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);

        new Login().setVisible(true);
        this.dispose();
    }//GEN-LAST:event_signUpjButtonActionPerformed

