    private boolean isUserExists(String userName) {
        try {
            java.io.File file = new java.io.File("resources/users.txtt");
            if (!file.exists()) {
                return false;
            }
            java.util.Scanner sc = new java.util.Scanner(file);
            while (sc.hasNextLine()) {
                String[] parts = sc.nextLine().split(":");
                if (parts[0].equals(userName)) {
                    return true;
                }
            }
        } catch (FileNotFoundException ex) {
        }
        return false;
    }

    private void saveUser(String userName, String password) {
        try {
            java.io.File file = new java.io.File("resources/users.txt");

            System.out.println("Saving to: " + file.getAbsolutePath());

            try (java.io.FileWriter writer = new java.io.FileWriter(file, true)) {
                writer.write(userName + ":" + password + "\n");
            }

        } catch (IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error saving user: " + ex.getMessage(), "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
